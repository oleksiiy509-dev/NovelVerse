using (lower(status) = 'published');

drop policy if exists "Owners manage chapters" on public.chapters;
create policy "Owners manage chapters" on public.chapters for all to authenticated
using (exists (select 1 from public.novels n where n.id = novel_id and (n.owner_id = auth.uid() or public.is_admin())))
with check (exists (select 1 from public.novels n where n.id = novel_id and (n.owner_id = auth.uid() or public.is_admin())));
drop policy if exists "Anyone can view chapters of published books" on public.chapters;
create policy "Anyone can view chapters of published books" on public.chapters for select
using (exists (select 1 from public.novels n where n.id = novel_id and lower(n.status) = 'published'));

drop policy if exists "Owners manage publication events" on public.publication_events;
create policy "Owners manage publication events" on public.publication_events for all to authenticated
using (exists (select 1 from public.novels n where n.id = novel_id and (n.owner_id = auth.uid() or public.is_admin())))
