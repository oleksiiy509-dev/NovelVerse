-- Keep the authorization helper self-contained so this single migration can be
-- applied even when the older production-readiness migration was not deployed.
create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false)
      or coalesce((auth.jwt() -> 'app_metadata' ->> 'is_admin') = 'true', false)
      or exists (
        select 1 from public.user_roles r
        where r.user_id = auth.uid() and r.role = 'admin'
      );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.set_creator_portal_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists novels_creator_updated_at on public.novels;
create trigger novels_creator_updated_at before update on public.novels
for each row execute function public.set_creator_portal_updated_at();
drop trigger if exists chapters_creator_updated_at on public.chapters;
create trigger chapters_creator_updated_at before update on public.chapters
for each row execute function public.set_creator_portal_updated_at();
drop trigger if exists chapter_audio_creator_updated_at on public.chapter_audio;
create trigger chapter_audio_creator_updated_at before update on public.chapter_audio
for each row execute function public.set_creator_portal_updated_at();
drop trigger if exists audio_jobs_creator_updated_at on public.audio_render_jobs;
create trigger audio_jobs_creator_updated_at before update on public.audio_render_jobs
for each row execute function public.set_creator_portal_updated_at();

insert into storage.buckets (id, name, public)
values ('book-assets', 'book-assets', true)
on conflict (id) do update set public = excluded.public;
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
