alter table public.audio_render_segments add column if not exists retry_count integer not null default 0;
alter table public.audio_render_segments add column if not exists error_message text;

create index if not exists chapter_audio_chapter_status_idx on public.chapter_audio(chapter_id, status, updated_at desc);
create index if not exists chapter_audio_novel_idx on public.chapter_audio(novel_id, language, voice_id);
create index if not exists chapter_audio_ready_idx on public.chapter_audio(chapter_id) where status = 'ready';
create index if not exists audio_render_jobs_status_priority_idx on public.audio_render_jobs(status, priority desc, created_at);
create index if not exists audio_render_jobs_chapter_idx on public.audio_render_jobs(chapter_id, language, provider);
create index if not exists audio_render_jobs_created_by_idx on public.audio_render_jobs(created_by, created_at desc);
create index if not exists audio_render_segments_job_index on public.audio_render_segments(job_id, segment_index);
create index if not exists audio_render_segments_chapter_idx on public.audio_render_segments(chapter_id, segment_index);

